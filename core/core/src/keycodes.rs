#[cfg(test)]
mod tests {
    use super::*;

    #[test]
    fn round_trips_through_the_table() {
        for code in [0x00u16, 0x31, 0x35, 0x7B, 0x24] {
            let name = name_for(code).expect("name");
            let key: handy_keys::Key = name.parse().expect("key");
            assert_eq!(code_for(&key), Some(code), "{name} should round-trip");
        }
    }

    #[test]
    fn unknown_codes_have_no_name() {
        assert_eq!(name_for(0xFFFF), None);
    }
}
